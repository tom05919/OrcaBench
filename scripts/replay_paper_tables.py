#!/usr/bin/env python3
"""Write the class report's results table (LaTeX) from scripts/replay_analyze.py's summary.

  python3 scripts/replay_paper_tables.py --summary results/w1/replay/summary.json --out docs/cos597c_report/results_table.tex

One row per model and requested reasoning level (none, low, high; GLM's none is `minimal`): the manipulation check
(median thinking characters on the probe), probe balanced accuracy and its paired difference from the model's none
level, and the leave-alone session measures at 2 s per look."""
import argparse
import json
from pathlib import Path

MODELS = [("moonshotai/Kimi-K3", "Kimi K3"), ("google/gemma-4-31B-it", "Gemma 4 31B"),
          ("deepseek-ai/DeepSeek-V4.1-Flash-1017", "DeepSeek V4.1 Flash"), ("zai-org/GLM-5.3-Flash", "GLM-5.3 Flash")]


def grid(model):
    return ["minimal" if "GLM" in model else "off", "low", "high"]


def ci(d, signed=False):
    f = "{:+.3f}" if signed else "{:.3f}"
    return f"{f.format(d['mean'])} [{f.format(d['ci95'][0])}, {f.format(d['ci95'][1])}]".replace("-", "$-$")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--summary", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    s = json.loads(args.summary.read_text())
    rows = []
    for model, name in MODELS:
        for i, e in enumerate(grid(model)):
            p = s["probe"][f"{model}|{e}|pass1"]
            la = s["sessions"][f"{model}|{e}|c2"]["leave-alone"]
            diff = "---" if i == 0 else ci(s["probe_contrasts"][f"{model}|{e} - {grid(model)[0]}"], signed=True)
            level = {"off": "none", "minimal": "none (min.)"}.get(e, e)
            n = "" if la["episodes"] == 72 else f"$^{{n={la['episodes']}}}$"
            rows.append(f"{name if i == 0 else ''} & {level} & {p['median_thinking_chars']:,.0f} & "
                        f"{ci(p['balanced_accuracy'])} & {diff} & {ci(la['minus_detector'], signed=True)}{n} & "
                        f"{la['looks_per_episode']:.1f} & {100 * la['success_on_succeeding_runs']:.0f} \\\\")
        rows.append("\\midrule" if model != MODELS[-1][0] else "\\bottomrule")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("% Generated by scripts/replay_paper_tables.py; do not edit by hand.\n" + "\n".join(rows) + "\n")
    print("wrote", args.out)


if __name__ == "__main__":
    main()
